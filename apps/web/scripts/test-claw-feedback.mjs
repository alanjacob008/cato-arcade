import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import ts from "typescript";
import * as THREE from "three";
const compile = async name => ts.transpileModule(await readFile(new URL(`../components/claw/${name}.ts`, import.meta.url), "utf8"), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const url = js => `data:text/javascript;base64,${Buffer.from(js).toString("base64")}`;
const { cabinetFeedback: lighting, CABINET_FEEDBACK_DURATION, CUES, noteFrequency, marqueeSweep, MARQUEE_SWEEP_PERIOD } = await import(url(await compile("feedback")));
assert.equal(CABINET_FEEDBACK_DURATION, 2000);
assert.equal(MARQUEE_SWEEP_PERIOD, 4000);
assert.equal(marqueeSweep(0, 0, 7), 1);
assert.equal(marqueeSweep(1200, 3, 7), 1);
assert.equal(marqueeSweep(2400, 6, 7), 1);
assert.equal(marqueeSweep(3200, 3, 7), 0);
assert.equal(marqueeSweep(4000, 0, 7), 1);
assert.equal(marqueeSweep(100, 0, 7, true), marqueeSweep(2800, 6, 7, true), "Reduced motion keeps marquee bulbs steady");
assert.equal(lighting(0, null, 0).light, 0, "Standby cabinet is unlit");
assert(lighting(1, null, 0).light > 0, "Inserted token powers cabinet");
assert.equal(lighting(1, true, 700).color, "#39ff88");
assert.equal(lighting(1, false, 700).color, "#ff3355");
assert.equal(lighting(1, null, 0).color, "#FEA911", "The idle cabinet glow is the arcade's amber, never violet");
assert(lighting(1, true, 700).light > lighting(1, null, 0).light, "Result is neon bright");
assert.equal(lighting(0, true, CABINET_FEEDBACK_DURATION).active, false);
assert.equal(lighting(0, false, CABINET_FEEDBACK_DURATION).light, 0, "Returns to standby after feedback");
assert.equal(lighting(1, true, 100, true).light, lighting(1, true, 1700, true).light, "Reduced motion has no flashing");
let peaks = 0;
for (let ms = 10; ms < CABINET_FEEDBACK_DURATION - 10; ms += 10) if (lighting(1, true, ms).light > lighting(1, true, ms - 10).light && lighting(1, true, ms).light >= lighting(1, true, ms + 10).light) peaks++;
assert.equal(peaks, 4, "Four brief bursts over two seconds");
assert.equal(noteFrequency(69), 440);
const winMelody = CUES.win.filter(note => note.wave === "square");
assert(winMelody.at(-1).midi > winMelody[0].midi, "Win melody ascends above its opening note, independently of the bass");
assert(CUES.miss.at(-1).midi < CUES.miss[0].midi, "Miss chime descends");
for (const notes of Object.values(CUES)) for (const note of notes) assert(note.at >= 0 && note.duration > .006 && note.gain > 0 && note.gain <= .15 && Number.isFinite(noteFrequency(note.midi)));
const surface = url((await compile("materialTextures")).replace('"three"', JSON.stringify(import.meta.resolve("three"))));
const config = url(await compile("config"));
const { boxDeliveryHeight, boxDropMotion, restingBoxRotation } = await import(url((await compile("delivery")).replace('"./config"', JSON.stringify(config)).replace('"three"', JSON.stringify(import.meta.resolve("three")))));
const { POCKET, MACHINE } = await import(config);
for (const rotation of [new THREE.Euler(), new THREE.Euler(Math.PI / 2, 0, 0), new THREE.Euler(.4, .3, .7)]) {
  const q = new THREE.Quaternion().setFromEuler(rotation), height = boxDeliveryHeight(q);
  let min = Infinity;
  for (const x of [-1, 1]) for (const y of [-1, 1]) for (const z of [-1, 1]) min = Math.min(min, new THREE.Vector3(x, y, z).multiplyScalar(MACHINE.boxSize / 2).applyQuaternion(q).y + height);
  assert(Math.abs(min - POCKET.floorY) < 1e-9, "Rotated box lands intact without going through floor");
  const resting = restingBoxRotation(q), restingHeight = boxDeliveryHeight(resting);
  assert(Math.abs(restingHeight - POCKET.floorY - MACHINE.boxSize / 2) < 1e-9, "Delivered boxes settle onto their nearest flat face");
}
const dropStart = 3.3, landingY = -.5, hitTime = Math.sqrt(2 * (dropStart - landingY) / 9.81);
assert.equal(boxDropMotion(dropStart, landingY, 0).y, dropStart);
assert(Math.abs(boxDropMotion(dropStart, landingY, .2).y - (dropStart - .5 * 9.81 * .2 ** 2)) < 1e-9, "Free fall follows gravity");
assert(boxDropMotion(dropStart, landingY, hitTime + .08).y > landingY, "One low bounce follows impact");
for (let t = 0; t < 1.5; t += .01) assert(boxDropMotion(dropStart, landingY, t).y >= landingY, "Never falls through the prize floor");
assert.deepEqual(boxDropMotion(dropStart, landingY, 1.5), { y: landingY, contact: true, settle: 1, done: true });
console.log("PASS: two-second interior/marquee flicker, green/red outcomes, reduced motion, pixel cues, gravity, low bounce, floor clearance and flat-face settling.");
const prizeModelSource = (await compile("prizeModel")).replace('"three"', JSON.stringify(import.meta.resolve("three"))).replace('"three/addons/geometries/RoundedBoxGeometry.js"', JSON.stringify(import.meta.resolve("three/addons/geometries/RoundedBoxGeometry.js"))).replace('"three/addons/utils/BufferGeometryUtils.js"', JSON.stringify(import.meta.resolve("three/addons/utils/BufferGeometryUtils.js"))).replace('"./config"', JSON.stringify(config));
const prizeModel = url(prizeModelSource);
const { createPrizeGeometry } = await import(prizeModel);
const packageGeometry = createPrizeGeometry();
assert.equal(packageGeometry.groups.length, 3, "Collector boxes have shell, face-panel and metal-frame material groups");
for (const axis of ["x", "y", "z"]) assert(packageGeometry.boundingBox.max[axis] <= MACHINE.boxSize / 2 + 1e-6 && packageGeometry.boundingBox.min[axis] >= -MACHINE.boxSize / 2 - 1e-6, "Detailed packages retain the original physics envelope");
packageGeometry.dispose();
const appearanceSource = (await compile("prizeAppearance")).replace('"./prizeModel"', JSON.stringify(prizeModel)).replace('"./materialTextures"', JSON.stringify(surface)).replace('"three"', JSON.stringify(import.meta.resolve("three")));
const { createPrizeAppearance } = await import(url(appearanceSource));
const appearance = createPrizeAppearance(), purple = appearance.material("#7950b4"), white = appearance.material("#f5f1fa"), orange = appearance.material("#ee9951");
assert.equal(purple.color.getHexString(), "7950b4", "High-tier boxes keep their canonical purple tier color");
assert.equal(purple.map, null, "The Solana gradient no longer covers prize boxes");
assert.equal(appearance.material("#7950b4"), purple, "Share surface resources across boxes");
assert.equal(white.color.getHexString(), "f5f1fa"); assert.equal(orange.color.getHexString(), "ee9951");
appearance.update(1); assert.equal(white.emissiveIntensity, 0, "White collector packs remain physical paper, without fluorescent outlines"); assert(purple.emissiveIntensity > 0);
assert.equal(white.emissiveMap, null); assert.equal(orange.emissiveMap, null);
[purple, white, orange].forEach(material => material.dispose());
console.log("PASS: purple high-tier boxes, preserved lower-tier colors, powered box glow and shared GPU resources.");
