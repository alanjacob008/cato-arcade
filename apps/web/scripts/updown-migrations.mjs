// Bundles apps/updown/db/*.sql into lib/updownMigrations.generated.mjs, because the
// website's serverless functions cannot read files outside their bundle at
// runtime. Run by scripts/build-updown.mjs on every build; a unit test fails if
// the committed file drifts from the SQL. Usage: node scripts/updown-migrations.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const SQL_DIR = resolve(here, "../../updown/db");
export const OUTPUT = resolve(here, "../lib/updownMigrations.generated.mjs");

export function renderMigrations(directory = SQL_DIR) {
  const files = readdirSync(directory).filter((f) => f.endsWith(".sql")).sort();
  const entries = files.map((name) => {
    const sql = readFileSync(join(directory, name), "utf8").replace(/\r\n/g, "\n");
    return `  { name: ${JSON.stringify(name)}, sql: ${JSON.stringify(sql)} },`;
  });
  return [
    "// GENERATED by scripts/updown-migrations.mjs from apps/updown/db/*.sql. Do not edit.",
    "export const MIGRATIONS = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

export function writeMigrations() {
  writeFileSync(OUTPUT, renderMigrations());
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeMigrations();
  console.log(`[updown] wrote ${OUTPUT}`);
}
